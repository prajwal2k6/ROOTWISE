
const API_BASE_URL = (
  process.env.NEXT_PUBLIC_API_URL || "http://127.0.0.1:8000"
).replace(/\/+$/, "");

export type CropDetail = {
  name: string;
  family: string;
};

export type RotationPathway = {
  number: string;
  strategy?: string;
  title: string;
  sequence: string;
  purpose: string;
  summary?: string;
  benefits?: string[];
  risks?: string[];
  checks: string[];
  crops: string[];
  crop_details: CropDetail[];
  phase_reasons: string[];
  confidence?: string | {
    level?: string;
    explanation?: string;
  };
  evidence?: string[];
};

type RotationAPIResponse = {
  farm?: Record<string, unknown>;
  pathways?: Array<{
    number?: string;
    strategy?: string;
    title?: string;
    sequence?: string;
    purpose?: string;
    summary?: string;
    benefits?: string[];
    risks?: string[];
    checks?: string[];
    crops?: string[];
    crop_details?: CropDetail[];
    phase_reasons?: string[];
    confidence?: string | {
      level?: string;
      explanation?: string;
    };
    evidence?: string[];
  }>;
};

export async function getSuggestedPathways(
  farmId: number | string,
  accessToken: string
): Promise<RotationPathway[]> {
  const response = await fetch(
    `${API_BASE_URL}/api/rotation-matchmaker/${farmId}`,
    {
      method: "GET",
      headers: {
        Authorization: `Bearer ${accessToken}`,
        "Content-Type": "application/json",
      },
    }
  );

  if (!response.ok) {
    const error = await response.text();

    throw new Error(
      error || "Failed to load crop rotation recommendations."
    );
  }

  const data: RotationAPIResponse = await response.json();

  return (data.pathways ?? []).map((pathway, index) => ({
    number:
      pathway.number ?? String(index + 1).padStart(2, "0"),

    strategy: pathway.strategy,

    title: pathway.title ?? "Crop rotation pathway",

    sequence:
      pathway.sequence ??
      (pathway.crops ?? []).join(" → "),

    purpose: pathway.purpose ?? pathway.summary ?? "",

    summary: pathway.summary,

    benefits: pathway.benefits ?? [],

    risks: pathway.risks ?? [],

    checks: pathway.checks ?? [],

    crops: pathway.crops ?? [],

    crop_details: pathway.crop_details ?? [],

    // IMPORTANT: Preserve the explanations generated by the backend.
    phase_reasons: pathway.phase_reasons ?? [],

    // Backend confidence is an object, not always a string.
    confidence: pathway.confidence,

    evidence: pathway.evidence ?? [],
  }));
}
